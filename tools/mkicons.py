#!/usr/bin/env python3
"""Convert fonts/icons.txt into C tables for the kernel.

Usage: mkicons.py INPUT.txt OUTPUT.c

Each icon becomes "const struct icon icon_NAME": width, height and the
pixels, one bit each, rows padded to whole bytes, leftmost pixel in bit 7.
"""
import sys


def parse(path):
    icons, name = {}, None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#") or not line.strip():
            continue
        if line.startswith("icon "):
            name = line.split()[1]
            icons[name] = []
        else:
            assert name and set(line) <= set("X."), "bad line: " + line
            icons[name].append(line)
    for name, rows in icons.items():
        assert rows and len({len(r) for r in rows}) == 1, "rows of %s differ in length" % name
        assert len(rows[0]) <= 255 and len(rows) <= 255
    return icons


def main():
    icons = parse(sys.argv[1])
    out = ["/* Generated by tools/mkicons.py from fonts/icons.txt - do not edit. */",
           "struct icon { unsigned char w, h; const unsigned char *bits; };", ""]
    for name, rows in icons.items():
        data = []
        for r in rows:
            r = r + "." * (-len(r) % 8)
            data += [int(r[i:i + 8].replace("X", "1").replace(".", "0"), 2) for i in range(0, len(r), 8)]
        out.append("static const unsigned char bits_%s[] = {" % name)
        for i in range(0, len(data), 16):
            out.append("    " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
        out.append("};")
        out.append("const struct icon icon_%s = {%d, %d, bits_%s};" % (name, len(rows[0]), len(rows), name))
        out.append("")
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
