#!/usr/bin/env python3
"""Convert fonts/juan6x10.txt into a C table for the kernel console.

Usage: mkfont.py INPUT.txt OUTPUT.c

Output: font6x10[224][10], one entry per character code from 32 to 255 (see
tools/juanterm/charset.py for which character has which code). Entry 95
(code 127) is a solid block, used for codes that have no character. Each
byte is one row of the 6 x 10 cell with the leftmost pixel in bit 7; bits
1-0 are unused.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "juanterm"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import charset  # noqa: E402
from juanterm import vt  # noqa: E402

CELL_W, CELL_H = 6, 10
GLYPH_W, GLYPH_ROWS = 5, 9


def parse(path):
    """Return {character: rows}. A glyph drawn 5 wide has 9 rows and sits
    below a blank top row; one drawn 6 wide has 10 rows and fills the cell."""
    glyphs, name, rows = {}, None, []

    def finish():
        if name is None:
            return
        assert name not in glyphs, f"duplicate glyph {name!r}"
        width = len(rows[0]) if rows else GLYPH_W
        height = CELL_H if width == CELL_W else GLYPH_ROWS
        assert width in (GLYPH_W, CELL_W), f"glyph {name!r} is {width} wide"
        assert len(rows) <= height, f"glyph {name!r} has {len(rows)} rows"
        for r in rows:
            assert len(r) == width and set(r) <= {".", "X"}, f"bad row {r!r} in {name!r}"
        glyphs[name] = rows + ["." * width] * (height - len(rows))

    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith(";;") or not line.strip():
            continue
        if line.startswith("= "):
            finish()
            name = line[2:]
            name = " " if name == "space" else name
            assert len(name) == 1, f"bad glyph name {line!r}"
            rows = []
        else:
            rows.append(line)
    finish()
    return glyphs


def cell(rows):
    """The ten bytes of a glyph's cell."""
    if len(rows[0]) == CELL_W:
        return [int(r.replace("X", "1").replace(".", "0") + "00", 2) for r in rows]
    return [0] + [int(r.replace("X", "1").replace(".", "0") + "000", 2) for r in rows]


def main():
    glyphs = parse(sys.argv[1])
    glyphs[" "] = glyphs[" "]          # no-break space
    glyphs["­"] = glyphs["-"]          # soft hyphen
    wanted = [charset.char(c) for c in range(32, 256)]
    missing = [ch for ch in wanted if ch is not None and ch not in glyphs]
    assert not missing, f"font is missing {missing}"
    unused = sorted(set(glyphs) - set(wanted))
    assert not unused, f"font has glyphs with no character code: {unused}"

    out = ["/* Generated by tools/mkfont.py from fonts/juan6x10.txt - do not edit. */",
           "const unsigned char font6x10[224][10] = {"]
    for code in range(32, 256):
        ch = charset.char(code)
        if ch is None:
            bits, label = [0xFC] * CELL_H, "block"
        else:
            bits = cell(glyphs[ch])
            label = "U+%04X" % ord(ch) if code >= 127 or ch in "\\/*" else ch
        row = ",".join(f"0x{b:02x}" for b in bits)
        out.append(f"    {{{row}}},  /* {code} {label} */")
    out.append("};")
    out.append("")
    out.append("/* The Unicode characters of codes 0x80-0x9F, from tools/juanterm/charset.py. */")
    out.append("const unsigned short charset_extra[32] = {")
    out.append("    " + ", ".join("0x%04X" % ord(ch) for ch in charset.EXTRA[:16]) + ",")
    out.append("    " + ", ".join("0x%04X" % ord(ch) for ch in charset.EXTRA[16:]) + ",")
    out.append("};")
    # Line drawing and blocks come in many weights (double, heavy, dashed);
    # the font has one. The nearest character of ours for each, worked out
    # by the rules in tools/juanterm/vt.py.
    box = [(vt._map_cp(cp) + (63,))[0] for cp in range(0x2500, 0x25A0)]
    out.append("")
    out.append("/* Our character for each of U+2500-U+259F (box drawing and blocks). */")
    out.append("const unsigned char charset_box[160] = {")
    for i in range(0, 160, 16):
        out.append("    " + ",".join("0x%02X" % c for c in box[i:i + 16]) + ",")
    out.append("};")
    with open(sys.argv[2], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
