#!/usr/bin/env python3
"""Work out what in the kernel takes how much memory, for the panel that
opens from "Mem" on the bar.

    mkmem.py SIZE-PROGRAM OUTPUT.c OBJECT...

Runs the size program (m68k-elf-size) on the kernel's object files, adds up
code, tables and working memory for each part of the system, and writes them
as a C table, largest first. Nothing in SSH OS asks for memory while it runs:
every part's share is fixed when it is built, which is why this can be done
here.
"""
import os
import subprocess
import sys

PARTS = [
    ("SSH", "ssh connect ask"),
    ("Ciphers for SSH", "x25519 ed25519 sha256 sha512 poly1305 rng"),
    ("Network", "net tcp dayna wifi http cmd_tcp"),
    ("Terminal", "vt console term"),
    ("Screen, icons and font", "gfx bar barmenu desk settings splash banner icons font6x10"),
    ("Disk and settings", "scsi fs saved config cfgdata"),
    ("Home Assistant panel", "home"),
    ("OSConsole and tests", "shell hwtest bench"),
]
REST = "Keyboard, mouse, the rest"


def main():
    size, out = sys.argv[1], sys.argv[2]
    which = {name: label for label, names in PARTS for name in names.split()}
    total = {}
    for line in subprocess.run([size] + sys.argv[3:], check=True, stdout=subprocess.PIPE,
                               universal_newlines=True).stdout.splitlines()[1:]:
        f = line.split()
        name = os.path.splitext(os.path.basename(f[5]))[0]
        label = which.get(name, REST)
        total[label] = total.get(label, 0) + int(f[3])
    rows = sorted(total.items(), key=lambda kv: -kv[1])
    c = ["/* Generated by tools/mkmem.py - do not edit. */",
         "struct mem_part { const char *name; unsigned long bytes; };",
         "const struct mem_part mem_parts[] = {"]
    c += ['    {"%s", %d},' % kv for kv in rows]
    c += ["};", "const int mem_nparts = %d;" % len(rows)]
    with open(out, "w") as f:
        f.write("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
